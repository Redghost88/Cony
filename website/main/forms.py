"""
Формы приложения
"""

from django import forms
from django.contrib.auth.models import User
from django.contrib.auth.forms import UserCreationForm
from main.models import Profile


class LoginForm(forms.Form):
    """
    Форма для аутентификации пользователя в системе.

    Используется для сбора учетных данных (логина и пароля) и их последующей
    валидации перед выполнением входа.

    Атрибуты формы:
        username (CharField): Поле для ввода логина.
            - Ограничение по длине: 256 символов.
            - Метка (label): "Логин".
        password (CharField): Поле для ввода пароля.
            - Ограничение по длине: 256 символов.
            - Метка (label): "Пароль".
            - Виджет: PasswordInput (скрывает символы при вводе).

    Примечание:
        Хотя внутри класса указан атрибут `model = User`, стандартный `forms.Form`
        не использует это поле автоматически (в отличие от `ModelForm`).
        Атрибут служит в качестве метаинформации для логики аутентификации во view.
    """

    model = User
    username = forms.CharField(label="Логин", max_length=256)
    password = forms.CharField(
        label="Пароль", max_length=256, widget=forms.PasswordInput
    )


class RegisterForm(UserCreationForm):
    """
    Форма для регистрации нового пользователя на базе встроенной формы Django.

    Наследуется от `UserCreationForm`, что обеспечивает автоматическую
    валидацию уникальности имени пользователя, проверку совпадения паролей
    и безопасное хэширование пароля перед сохранением в базу данных.

    Метаданные (Meta):
        model (User): Указывает на стандартную модель пользователя Django
            (или кастомную, если она настроена в проекте).
        fields (list): Определяет список полей, которые будут отображены в форме.
            - "username": Уникальное имя пользователя для входа.
            - "email": Адрес электронной почты пользователя.

    Особенности:
        - Поля пароля ('password1' и 'password2') добавляются автоматически
          родительским классом UserCreationForm.
        - Форма автоматически выполняет очистку (clean) данных и возвращает
          объект пользователя при вызове метода save().
    """

    class Meta:
        model = User
        fields = ["username", "email"]


class ProfileUpdateForm(forms.ModelForm):
    """
    Форма для редактирования данных профиля пользователя.

    Базируется на модели `Profile` и используется для обновления личной
    информации пользователя (в частности, изображения профиля) через веб-интерфейс.

    Метаданные (Meta):
        model (Profile): Указывает на модель профиля, с которой связана форма.
        fields (list): Определяет список редактируемых полей.
            - "avatar": Поле для загрузки и обновления изображения профиля.

    Особенности:
        - Поскольку форма работает с файлами (ImageField), при её инициализации
          в шаблоне необходимо использовать атрибут `enctype="multipart/form-data"`.
        - При сохранении формы Django автоматически обрабатывает загрузку файла,
          удаление старого (если настроено) и обновление пути в базе данных.
    """

    class Meta:
        model = Profile
        fields = ["avatar"]
